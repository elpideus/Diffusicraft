package io.github.elpideus.diffusicraft.client.mixin;

import io.github.elpideus.diffusicraft.worldgen.DiffusicraftWorldgen;
import net.minecraft.client.gui.screens.worldselection.WorldCreationUiState;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.levelgen.presets.WorldPreset;
import net.minecraft.world.level.levelgen.presets.WorldPresets;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.ModifyVariable;

import java.util.Optional;

/**
 * Makes Diffusicraft the world type a new world starts with. The constructor applies the preset's dimensions, so the
 * world is generated by Diffusicraft unless the player picks another type. Re-created worlds keep their own preset.
 */
@Mixin(WorldCreationUiState.class)
abstract class WorldCreationUiStateMixin {
	@ModifyVariable(method = "<init>", at = @At("HEAD"), argsOnly = true)
	private static Optional<ResourceKey<WorldPreset>> diffusicraft$defaultPreset(Optional<ResourceKey<WorldPreset>> preset) {
		return preset.filter(key -> !key.equals(WorldPresets.NORMAL)).or(() -> Optional.of(DiffusicraftWorldgen.STANDARD_PRESET));
	}
}
